const {chromium} = require(process.env.PLAYWRIGHT_PATH || 'playwright-core');
const {normalized} = require('../viewer/letters.js');
const fs = require('fs');
const path = require('path');
const out = process.env.HEADLESS_OUTPUT || path.join(__dirname, '../output/headless');
fs.mkdirSync(out,{recursive:true});
(async()=>{
 const browser = await chromium.launch({headless:true,chromiumSandbox:true});
 const page = await browser.newPage({viewport:{width:1365,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const assert=(condition,message)=>{if(!condition)throw new Error(message);};
 const waitCount=async text=>page.waitForFunction(t=>document.getElementById('result-count').textContent===t,text);
 const overflow=async()=>page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth}));
 await page.goto(process.env.VIEWER_URL || 'http://127.0.0.1:8766',{waitUntil:'networkidle'});
 await waitCount('54,564 results');
 assert(await page.locator('.row').count()===50,'50-row paging');
 assert(JSON.stringify(await page.locator('#direction option').evaluateAll(ns=>ns.map(n=>n.value)))===JSON.stringify(['','forward','reverse']),'all direction options');
 let values=await page.locator('.row small').allTextContents();
 assert(values.every((v,i)=>i===0||parseFloat(values[i-1])>=parseFloat(v)),'descending score');
 await page.locator('#next').click();await page.waitForFunction(()=>document.getElementById('page').textContent.startsWith('2 /'));
 await page.locator('#previous').click();await page.waitForFunction(()=>document.getElementById('page').textContent.startsWith('1 /'));
 await page.locator('#direction').selectOption('forward');await page.locator('#position').selectOption('2');
 await page.locator('#q').fill('ἐράσαι');await waitCount('1 results');await page.getByRole('button',{name:/^ΕΡΑΣΑΙ/}).click();
 await page.locator('#detail .verse').last().waitFor();
 let marks=await page.locator('#detail mark').allTextContents();assert(normalized(marks.join(''))==='ΕΡΑΣΑΙ','Helen forward highlighted path');
 assert(await page.locator('#detail .verse').count()===6,'Helen six lines');
 const desktop=await overflow();assert(desktop.scrollWidth<=desktop.width,'desktop overflow');
 await page.screenshot({path:path.join(out,'desktop-helen.png'),fullPage:true});
 await page.locator('#direction').selectOption('reverse');await page.locator('#position').selectOption('1');
 await page.locator('#q').fill('ΕΚΤΩΡ');await waitCount('1 results');await page.getByRole('button',{name:/^ΕΚΤΩΡ/}).click();
 await page.waitForFunction(()=>document.querySelectorAll('#detail mark').length===5);
 marks=await page.locator('#detail mark').allTextContents();assert(normalized(marks.reverse().join(''))==='ΕΚΤΩΡ','reverse highlighted path');
 await page.locator('#q').fill('qqxx-no-result');await waitCount('0 results');
 await page.locator('[data-kind="isopsephy"]').click();await page.locator('#q').fill('8.39');
 await page.locator('#group_size').selectOption('2');await waitCount('1 results');await page.getByRole('button',{name:/^Poem 8\.39/}).click();
 await page.waitForFunction(()=>document.querySelectorAll('#detail .sum b').length===2);
 const sums=await page.locator('#detail .sum b').allTextContents();
 assert(sums[0]==='6,903 / 6,903'&&sums[1]==='6,903 / 6,913','AP8.39 both iota totals');
 await page.screenshot({path:path.join(out,'desktop-ap8-39.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.locator('[data-kind="acrostic"]').click();
 await page.locator('#direction').selectOption('forward');await page.locator('#position').selectOption('2');
 await page.locator('#q').fill('ΕΡΑΣΑΙ');await waitCount('1 results');await page.getByRole('button',{name:/^ΕΡΑΣΑΙ/}).click();
 await page.waitForFunction(()=>document.querySelectorAll('#detail mark').length===6);
 const mobile=await overflow();assert(mobile.scrollWidth<=mobile.width,'mobile overflow');
 await page.screenshot({path:path.join(out,'mobile-helen.png'),fullPage:true});
 assert(errors.length===0,'JS page errors: '+errors.join(';'));
 const result={browser:await browser.version(),mode:'separate headless Chromium, fresh context, chromiumSandbox:true',desktop,mobile,
 checks:['initial counts','50-row paging','descending score','next/previous page','accented Greek search','direction/position filters','forward highlights','reverse highlights','empty search','AP8.39 totals','mobile selection','no horizontal overflow','no JavaScript page errors'],screenshots:['desktop-helen.png','desktop-ap8-39.png','mobile-helen.png'],pageErrors:errors};
 fs.writeFileSync(path.join(out,'result.json'),JSON.stringify(result,null,2)+'\n');
 console.log(JSON.stringify(result));await browser.close();
})().catch(e=>{console.error(e.stack);process.exit(1);});
